/**
 * Такт: удары превращаются в счёт, который не рвётся, когда звук пропал.
 *
 * Инструмент играет по счёту, а не по звуку, и разница здесь принципиальная. Звук в зале
 * теряется постоянно: между треками, на брейке, на съеденной бочке, на закрытом ноутбуке.
 * Если считать только услышанное, экран на каждой такой дыре замирает, и зал видит не
 * инструмент, а зависшую программу.
 *
 * Поэтому такт держится маховиком. Пока длина такта известна, пропущенный удар дорисовывается
 * сам, ровно в свой срок. Снаружи разницы нет: наверх уходит счёт, и решения принимаются
 * по нему.
 *
 * Длину такта дают два источника. Слух умеет мерить темп целиком, автокорреляцией по всей
 * своей истории, и когда он в нём уверен, спорить с ним нечем: одна оценка по шести секундам
 * зала честнее, чем сумма промежутков между отдельными ударами, половина из которых пришлась
 * на снейр. Когда уверенности нет, работает старый способ: длина доучивается по живым
 * промежуткам, медленно, чтобы первая же пауза не увела счёт в темп, которого в зале нет.
 *
 * Фазу задаёт только живой удар. Дорисованный удар держит своё место, но, услышав живой рядом
 * с ним, маховик подтягивается к живому: иначе он идёт в верном темпе и мимо доли, а это
 * заметнее в зале, чем неверный темп.
 */

// Границы живого промежутка между ударами: от двухсот сорока ударов в минуту до сорока.
// Всё, что чаще, это дребезг одного удара, всё, что реже, это пауза, а не темп.
const GAP_RANGE = [250, 1500];

// Свой такт, пока о зале ничего не известно: чуть медленнее ста двадцати ударов в минуту.
const IDLE_PERIOD_MS = 500;

// Насколько услышанный промежуток двигает выученную длину такта.
const LEARN = 0.2;

// С какой уверенности слуха его темп считается известным. Ниже половины автокорреляция
// находит пик на шуме, и держаться за такой темп хуже, чем за собственные промежутки.
const TEMPO_TRUST = 0.5;

// Насколько за кадр длина такта идёт к темпу от слуха. За треть секунды доходит целиком,
// и смена трека не ломает счёт рывком.
const TEMPO_PULL = 0.05;

// Насколько живой удар, пришедший сразу после дорисованного, двигает фазу к себе. Целиком
// двигать нельзя: живой удар приходит с разбросом в несколько кадров, и маховик дёргался бы
// за каждым.
const PHASE_PULL = 0.4;

// Во сколько раз дольше своего срока ждать удар, прежде чем дорисовать его самому. Ждать
// ровно срок нельзя: живой удар всегда приходит с разбросом в несколько кадров, и маховик
// отбивал бы лишний удар перед каждым вторым настоящим.
const FILL_AFTER = 1.35;

// Возврат к своему темпу, когда удары дорисовываются один за другим: зал молчит, и держать
// темп прошлого трека дальше незачем.
const RELAX = 0.05;

const MS_PER_MINUTE = 60000;

export function createBeat() {
  let period = IDLE_PERIOD_MS;
  let at = 0;
  let count = 0;
  let heard = false;
  let locked = false;

  return {
    get count() {
      return count;
    },
    /** Темп в ударах в минуту: пульту, чтобы человек видел, во что попал инструмент. */
    get bpm() {
      return Math.round(MS_PER_MINUTE / period);
    },
    /** Слышит ли инструмент зал сейчас или держит такт сам. */
    get heard() {
      return heard;
    },
    /** Держится ли длина такта на измеренном темпе, а не на собственных промежутках. */
    get locked() {
      return locked;
    },
    /**
     * Кадр такта: удар случился или нет.
     *
     * Услышанный удар и дорисованный дальше неотличимы, и это сделано нарочно. Ходы, которые
     * принимаются на счёте, обязаны идти ровно, иначе на брейке инструмент замирает вместе
     * с музыкой, а на возврате бьёт всё разом.
     */
    tick({ hit, now, tempo = 0, confidence = 0 }) {
      locked = confidence >= TEMPO_TRUST && tempo > 0;
      if (locked) {
        const measured = MS_PER_MINUTE / tempo;
        period += (measured - period) * TEMPO_PULL;
      }

      const gap = now - at;
      if (hit && gap >= GAP_RANGE[0]) {
        if (!locked && gap <= GAP_RANGE[1]) period += (gap - period) * LEARN;
        at = now;
        count += 1;
        heard = true;
        return true;
      }
      // Живой удар вплотную за дорисованным это не новая доля, а поправка: маховик отбил
      // рано или поздно, и знать об этом можно только по нему.
      if (hit && !heard) at += (now - at) * PHASE_PULL;

      if (now - at < period * FILL_AFTER) return false;
      if (!locked) period += (IDLE_PERIOD_MS - period) * RELAX;
      at = now;
      count += 1;
      heard = false;
      return true;
    },
    reset() {
      count = 0;
      heard = false;
      locked = false;
      period = IDLE_PERIOD_MS;
    },
  };
}
