/**
 * Пункты набора афиши: что показано, каким кеглем и какой краской.
 *
 * Направление держит свои кегли в юнитах макета и свои краски из `inks`: это его почерк, и
 * пульт его не отменяет, а двигает. Множитель тянет пункт крупнее или мельче того кегля,
 * который назначило направление, поэтому ползунок работает одинаково и на трафарете, и на
 * поле, где строки набраны по-разному. Краска подменяет цвет, только когда её задали:
 * пустая краска оставляет пункту цвета направления, а не красит всё в одно.
 *
 * Список пунктов живёт здесь: пульт строит по нему ряды, отрисовка спрашивает по нему
 * состояние. Второго списка названий, который разъедется с первым, в проекте нет.
 */

export const TEXT_ROLES = [
  { id: 'name', label: 'Имя' },
  { id: 'meta', label: 'Служебка' },
  { id: 'credit', label: 'Подпись' },
];

// Множитель кегля: ниже трети строка пропадает с ногтя в ленте, выше двух с половиной имя
// вылезает за поля и режется краем кадра.
export const SCALE_RANGE = { min: 0.35, max: 2.5, step: 0.05 };
export const PLAIN_SCALE = 1;

/** Набор в исходном виде: всё показано, кегль и краска остаются за направлением. */
export function defaultText() {
  return Object.fromEntries(
    TEXT_ROLES.map(({ id }) => [id, { on: true, scale: PLAIN_SCALE, ink: null }]),
  );
}

export function createTypeset(text) {
  const item = (role) => text[role] ?? { on: true, scale: PLAIN_SCALE, ink: null };
  return {
    show: Object.fromEntries(TEXT_ROLES.map(({ id }) => [id, item(id).on])),
    scale: (role) => item(role).scale,
    ink: (role, own = null) => item(role).ink ?? own,
  };
}
