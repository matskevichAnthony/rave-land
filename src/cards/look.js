/**
 * Компоновка карточки: куда встанет имя, каким кеглем и где лягут знак и номер.
 *
 * Раньше эти числа были константами направлений, и новый сид менял только зерно и рельсу:
 * шесть бросков подряд давали шесть одинаковых макетов. Теперь раскладка тянется из своего
 * потока случайности. Поток отдельный намеренно: пульт умеет перебросить одну компоновку,
 * не трогая фактуру и цвет, и наоборот.
 *
 * Диапазоны узкие и выбраны руками: имя не заезжает на подвал, знак не выпадает из полей.
 * Случайность здесь укрощённая: она двигает вёрстку, а не ломает её.
 */

export function createLook(random) {
  return {
    // Центр имени по высоте. Ниже 0.7 имя дерётся с подвалом, выше 0.3 с шапкой.
    nameCenter: random.range(0.32, 0.68),
    // Множитель потолка кегля имени: серия дышит от сдержанной до плакатной.
    nameScale: random.range(0.72, 1.35),
    // Лёгкий наклон имени в радианах: заметен, но не роняет строку.
    tilt: random.range(-0.035, 0.035),
    // Призрачный номер: масштаб и снос базовой линии в долях высоты.
    numberScale: random.range(0.5, 1.2),
    numberDrift: random.range(-0.12, 0.05),
    // Знак: множитель высоты и сторона, к которой он прижат.
    logoScale: random.range(0.65, 1.5),
    logoRight: random() < 0.35,
    // Горизонтальный снос акцентов в долях ширины.
    drift: random.range(-0.05, 0.05),
    // Железо: верх плиты в долях высоты.
    plateTop: random.range(0.56, 0.76),
    // Поле: масштаб предмета и его центр по высоте.
    objectScale: random.range(0.7, 1.45),
    objectCentre: random.range(0.3, 0.58),
  };
}
