/**
 * Вкладка, открытая до выкладки, забирает страницу заново.
 *
 * Модуль по требованию вкладка просит по тому имени, которое знала на момент открытия, а имя
 * несёт хеш сборки. После выкладки этого файла на сервере уже нет, и прогулка, выгрузка сцены
 * и кодировщик падают на пустом месте, хотя сайт цел и свежая вкладка работает. Vite сообщает
 * о таком промахе событием `vite:preloadError`, и ответ на него один: взять страницу заново,
 * из новой сборки. Сид живёт в адресе, поэтому после перезагрузки в кадре тот же зал.
 *
 * Перезагрузка ровно одна на вкладку: если чанка нет и в свежей сборке, это сломанная
 * выкладка, и крутить страницу по кругу вместо сообщения об ошибке нельзя. Событие остаётся
 * незаглушённым: пока страница не сменилась, о неудаче говорит сама сцена.
 */

const RELOADED_KEY = 'rave-land:stale-build-reloaded';

export function reloadOnStaleBuild() {
  window.addEventListener('vite:preloadError', () => {
    if (sessionStorage.getItem(RELOADED_KEY)) return;
    sessionStorage.setItem(RELOADED_KEY, '1');
    window.location.reload();
  });
}
